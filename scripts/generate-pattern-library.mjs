#!/usr/bin/env node

// Generates docs/pattern-library.md — the production pattern library (#223) — and
// enforces it in --check mode.
//
// The @beemvp/beeui-showcase Pattern Gallery is a real, typechecked reference application
// (37 screens across four domain packs). This turns it into a documented product
// surface: for every screen it records purpose, state contract, composition,
// responsive/accessibility guidance, the callback/ownership boundary, related
// components, source-ownership guidance, and the application logic intentionally
// left to the caller — with every entry linking to the executable Showcase source.
//
// Everything except the two prose fields (purpose, excluded application logic) is
// DERIVED from the screen sources by component-docs-lib.mjs, so a new/removed
// screen, a changed props contract, or a changed composition changes this file and
// fails the freshness check. The prose lives in docs/pattern-library.content.json.
//
// Two modes mirror scripts/generate-component-reference.mjs:
//   node scripts/generate-pattern-library.mjs           # (re)write the file
//   node scripts/generate-pattern-library.mjs --check    # fail if stale/incomplete

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { ROOT_DIR, PATTERN_PACKS, getPatternScreens } from './component-docs-lib.mjs';

export const OUTPUT_FILE = 'docs/pattern-library.md';
export const CONTENT_FILE = 'docs/pattern-library.content.json';

export const REQUIRED_SECTIONS = [
  'Purpose',
  'State contract',
  'Composition',
  'Ownership boundary',
  'Responsive',
  'Accessibility',
  'Related components',
  'Source ownership',
  'Excluded application logic',
];

const HEADER_NOTE =
  'Generated by scripts/generate-pattern-library.mjs from the apps/showcase/patterns sources and ' +
  'docs/pattern-library.content.json. Do not edit by hand; run `pnpm docs:patterns:generate`.';

const UNPUBLISHED_NOTE =
  'STATUS: BeeUI is pre-1.0 and UNPUBLISHED. The Pattern Gallery is an in-repo reference application, not a ' +
  'published template. Screens are original BeeUI compositions you own via source-ownership (`pnpm beeui add <component>`), ' +
  'not a redistributable third-party template.';

export function readContent(rootDir = ROOT_DIR) {
  return JSON.parse(fs.readFileSync(path.join(rootDir, CONTENT_FILE), 'utf8'));
}

function screenSection(screen, content) {
  const entry = content.screens[screen.slug];
  const title = screen.slug
    .replace(/-screen$/, '')
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
  const composition = screen.beeuiComponents.length
    ? screen.beeuiComponents.map((c) => `\`${c}\``).join(', ')
    : '_no direct @beemvp/beeui-ui imports (composed from local pattern components)_';
  const callbacks = screen.callbacks.length
    ? screen.callbacks.map((c) => `\`${c}\``).join(', ')
    : '_none_';
  const propsContract = screen.propsType
    ? `\`${screen.propsType}\` (fully controlled — state and data are caller-owned props).`
    : 'Controlled via caller-owned props.';

  return `### ${title}

- **Purpose:** ${entry.purpose}
- **State contract:** ${propsContract}
- **Composition:** ${composition}.
- **Ownership boundary:** the screen renders UI and raises intent through ${callbacks}; the caller owns the state and side effects behind them.
- **Responsive:** follows the [responsive layout contract](responsive-layout.md) (bounded content width, safe-area-aware shells).
- **Accessibility:** inherits the per-component [accessibility contract](accessibility-contract.md); no bespoke a11y overrides.
- **Related components:** see the [component reference](component-reference.md) entries for the composition above.
- **Source ownership:** copy the screen and its BeeUI parts into your app via \`pnpm beeui add <component>\`; the screen source is [\`${screen.file.replace('apps/showcase/', '')}\`](../${screen.file}).
- **Excluded application logic:** ${entry.excluded}
`;
}

export function buildDocument(rootDir = ROOT_DIR) {
  const screens = getPatternScreens(rootDir);
  const content = readContent(rootDir);
  const byPack = new Map(PATTERN_PACKS.map((pack) => [pack.id, []]));
  for (const screen of screens) byPack.get(screen.pack)?.push(screen);

  const packSections = PATTERN_PACKS.map((pack) => {
    const packScreens = byPack.get(pack.id) ?? [];
    const body = packScreens.map((screen) => screenSection(screen, content)).join('\n');
    return `## ${pack.title}

${packScreens.length} screens — source under [\`apps/showcase/patterns/${pack.id}\`](../apps/showcase/patterns/${pack.id}).

${body}`;
  }).join('\n');

  const index = PATTERN_PACKS.map((pack) => {
    const packScreens = byPack.get(pack.id) ?? [];
    return `- **${pack.title}** (${packScreens.length}): ${packScreens.map((s) => s.slug.replace(/-screen$/, '')).join(', ')}`;
  }).join('\n');

  return `<!-- ${HEADER_NOTE} -->

# BeeUI production pattern library

> ${screens.length} production screen patterns across ${PATTERN_PACKS.length} domain packs, composed entirely from public \`@beemvp/beeui-ui\` components. Each entry links to its executable, typechecked source in the [@beemvp/beeui-showcase](../apps/showcase) Pattern Gallery. Derived from the showcase pattern sources and docs/pattern-library.content.json; enforced by \`pnpm docs:patterns:check\`.

${UNPUBLISHED_NOTE}

Each pattern documents its purpose, state contract, composition, the callback
ownership boundary between the screen and the application, and the application
logic (data fetching, navigation, persistence, provider integration) it
intentionally leaves to the caller. The patterns are UI compositions only — BeeUI
owns no routing, data, or backend. For single components see the [component
reference](component-reference.md); for the enforcement rules see the [component
documentation contract](component-documentation-contract.md).

## Index

${index}

${packSections}`;
}

// --- Structural checks ------------------------------------------------------

export function runStructuralChecks(rootDir = ROOT_DIR) {
  const results = [];
  const add = (name, ok, detail = '') => results.push({ name, ok, detail });

  const screens = getPatternScreens(rootDir);
  const content = readContent(rootDir);
  const slugs = new Set(screens.map((s) => s.slug));
  const contentSlugs = new Set(Object.keys(content.screens ?? {}));

  const missing = [...slugs].filter((s) => !contentSlugs.has(s)).sort();
  add('every showcase screen has a content entry', missing.length === 0, missing.length ? `missing: ${missing.join(', ')}` : `${slugs.size} screens`);
  const extra = [...contentSlugs].filter((s) => !slugs.has(s)).sort();
  add('no content entries for unknown screens', extra.length === 0, extra.length ? `unknown: ${extra.join(', ')}` : '');

  const badProse = [...contentSlugs].filter((s) => !content.screens[s]?.purpose?.trim() || !content.screens[s]?.excluded?.trim()).sort();
  add('every screen entry has purpose + excluded', badProse.length === 0, badProse.length ? `incomplete: ${badProse.join(', ')}` : '');

  const noComposition = screens.filter((s) => s.beeuiComponents.length === 0 && !s.file.includes('/components/')).map((s) => s.slug);
  add('every screen composes @beemvp/beeui-ui components', noComposition.length === 0, noComposition.length ? `no @beemvp/beeui-ui: ${noComposition.join(', ')}` : '');

  const doc = buildDocument(rootDir);
  const perScreen = doc.split(/^### /m).slice(1);
  const sectionGaps = [];
  for (const block of perScreen) {
    const title = block.split('\n', 1)[0];
    for (const section of REQUIRED_SECTIONS) {
      if (!block.includes(`**${section}`)) sectionGaps.push(`${title}:${section}`);
    }
  }
  add('generated doc carries every required section', sectionGaps.length === 0, sectionGaps.length ? `gaps: ${sectionGaps.slice(0, 8).join(', ')}` : `${REQUIRED_SECTIONS.length} sections × ${perScreen.length} screens`);

  const ok = results.every((r) => r.ok);
  return { ok, results };
}

function main() {
  const check = process.argv.includes('--check');
  const outPath = path.join(ROOT_DIR, OUTPUT_FILE);
  const expected = buildDocument(ROOT_DIR);

  const structural = runStructuralChecks(ROOT_DIR);
  for (const r of structural.results) {
    process.stdout.write(`${r.ok ? 'ok  ' : 'FAIL'}  ${r.name}${r.detail ? ` — ${r.detail}` : ''}\n`);
  }

  if (check) {
    const actual = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
    const fresh = actual === expected;
    process.stdout.write(`${fresh ? 'ok  ' : 'FAIL'}  ${OUTPUT_FILE} is up to date\n`);
    if (!structural.ok || !fresh) {
      process.stdout.write('\nPattern library check FAILED. Run `pnpm docs:patterns:generate` and fill docs/pattern-library.content.json.\n');
      process.exit(1);
    }
    process.stdout.write('\nProduction pattern library check passed.\n');
    return;
  }

  fs.writeFileSync(outPath, expected);
  process.stdout.write(`\nWrote ${OUTPUT_FILE}.\n`);
  if (!structural.ok) process.exit(1);
}

const isCli = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) main();
