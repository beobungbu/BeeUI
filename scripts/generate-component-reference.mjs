#!/usr/bin/env node

// Generates docs/component-reference.md — the per-component documentation
// contract surface (#221) — and enforces it in --check mode.
//
// The documentation contract: every public @beemvp/beeui-ui component MUST document a
// fixed set of sections (purpose, import, API, source-ownership, dependencies /
// provider, accessibility, platform behavior, theme / density, behavior contract,
// executable examples, limitations, related patterns). Most of those are DERIVED
// from canonical sources (registry.json, index.ts, the showcase app) by
// component-docs-lib.mjs; the irreducible human prose lives in
// docs/component-reference.content.json. This generator joins the two so the doc
// cannot claim a component that does not exist, cite a symbol that is not exported,
// or drop a required section — and a NEW public component with no curated entry
// fails the check, so docs cannot silently lag the component set.
//
// Two modes mirror scripts/generate-llms-txt.mjs:
//   node scripts/generate-component-reference.mjs           # (re)write the file
//   node scripts/generate-component-reference.mjs --check    # fail if stale/incomplete

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { ROOT_DIR, getPublicComponents, buildShowcaseUsageIndex, usageForComponent } from './component-docs-lib.mjs';

export const OUTPUT_FILE = 'docs/component-reference.md';
export const CONTENT_FILE = 'docs/component-reference.content.json';

// The required documentation sections every component section must carry. These
// bold labels are what the structural check greps for, so renaming one here is a
// deliberate contract change that must be mirrored in the check + tests.
export const REQUIRED_SECTIONS = [
  'Purpose',
  'Import',
  'API',
  'Source ownership',
  'Dependencies / provider',
  'Accessibility',
  'Platform',
  'Theme / density',
  'Behavior contract',
  'Executable examples',
];

const HEADER_NOTE =
  'Generated by scripts/generate-component-reference.mjs from registry/registry.json, ' +
  'packages/ui/src/index.ts, the @beemvp/beeui-showcase app, and docs/component-reference.content.json. ' +
  'Do not edit by hand; run `pnpm docs:contract:generate`.';

const UNPUBLISHED_NOTE =
  'STATUS: BeeUI is pre-1.0 and UNPUBLISHED. No `@beemvp/beeui-*` package or CLI is on npm. The install / ' +
  'import lines below are release-ready-but-not-published targets; the working, in-repo path today is the ' +
  'source-ownership CLI (`pnpm beeui -- add <component>`).';

export function readContent(rootDir = ROOT_DIR) {
  return JSON.parse(fs.readFileSync(path.join(rootDir, CONTENT_FILE), 'utf8'));
}

// Ranks showcase example files so readers get a real screen/gallery fixture first
// and test files last (tests are executable examples too, but less illustrative).
function rankExample(file) {
  if (/\/patterns\//.test(file)) return 0;
  if (/-showcase\.tsx$/.test(file) || /component-gallery/.test(file)) return 1;
  if (/\/__tests__\//.test(file)) return 3;
  return 2;
}

function pickExamples(files, limit = 3) {
  return [...files].sort((a, b) => rankExample(a) - rankExample(b) || a.localeCompare(b)).slice(0, limit);
}

function providerLine(component) {
  if (component.name === 'safe-area') {
    return 'Exports `BeeUIProvider`, the application root that supplies safe-area measurement, the Toast runtime, and the shared anchored-overlay runtime. Mount it once at the top of the app.';
  }
  const peers = ['react', 'react-native', ...component.peerDependencies.filter((p) => p !== 'react' && p !== 'react-native')];
  const peerText = `Peer dependencies: ${peers.map((p) => `\`${p}\``).join(', ')}.`;
  const providerText = component.providerRequired
    ? ' Requires a [`BeeUIProvider`](../packages/ui/src/components/safe-area.tsx) ancestor (shared overlay / toast runtime).'
    : ' No provider required; `BeeUIProvider` is still the recommended application root.';
  const rd = component.registryDependencies.length
    ? ` Source-ownership pulls in registry dependencies: ${component.registryDependencies.map((d) => `\`${d}\``).join(', ')}.`
    : '';
  return peerText + providerText + rd;
}

function componentSection(component, content, usageIndex) {
  const entry = content.components[component.name];
  const importLine = `import { ${component.values.join(', ')} } from '@beemvp/beeui-ui';`;
  const examples = pickExamples(usageForComponent(component, usageIndex));
  const exampleLinks = examples.map((file) => `[\`${file.replace('apps/showcase/', '')}\`](../${file})`).join(', ');
  const apiTypes = component.types.length
    ? ` Typed props: ${component.types.map((t) => `\`${t}\``).join(', ')} (from [\`@beemvp/beeui-ui\`](../packages/ui/src/index.ts)).`
    : '';
  const limitations = entry.limitations ? `\n- **Limitations:** ${entry.limitations}` : '';
  const notes = entry.notes ? `\n- **Notes:** ${entry.notes}` : '';

  return `## \`${component.name}\`

- **Purpose:** ${entry.purpose}
- **Import:** \`${importLine}\`
- **API:** ${component.values.map((v) => `\`${v}\``).join(', ')} — source [\`${component.source}\`](../${component.source}).${apiTypes}
- **Source ownership:** \`${component.cliAdd}\` (copies the source file into your app; see [registry CLI](registry-cli.md)).
- **Dependencies / provider:** ${providerLine(component)}
- **Accessibility:** roles/states per the [accessibility contract](accessibility-contract.md); text honors font scaling ([dynamic type](dynamic-type.md)).
- **Platform (iOS / Android / Web):** see the [compatibility matrix](compatibility-matrix.md) and [web support contract](web-support-contract.md).${component.allSources.length > 1 ? ' Platform-split module (native/web files resolve at build time).' : ''}
- **Theme / density:** [theming](theming.md) · [density](density.md).
- **Behavior contract:** [component catalog](components.md).
- **Executable examples:** ${exampleLinks || '_none found in the showcase_'} (typechecked @beemvp/beeui-showcase fixtures).${limitations}${notes}
`;
}

export function buildDocument(rootDir = ROOT_DIR) {
  const components = getPublicComponents(rootDir);
  const content = readContent(rootDir);
  const usageIndex = buildShowcaseUsageIndex(rootDir);

  const sections = components.map((component) => componentSection(component, content, usageIndex)).join('\n');

  return `<!-- ${HEADER_NOTE} -->

# BeeUI component reference

> Per-component documentation contract for the ${components.length} public \`@beemvp/beeui-ui\` components. Each entry documents the same required sections so a new public component cannot silently ship without docs. Derived from registry/registry.json, packages/ui/src/index.ts, and the @beemvp/beeui-showcase app; enforced by \`pnpm docs:contract:check\`. The behavior-contract link points at the authoritative [component catalog](components.md); this file is the coverage-enforced per-component index, not a second copy of it.

${UNPUBLISHED_NOTE}

The documentation contract, its required sections, and how it is enforced are defined in [component-documentation-contract.md](component-documentation-contract.md). For the token-efficient name→symbol→source map see [llms-components.txt](../llms-components.txt); for composed screens see the [pattern library](pattern-library.md).

${sections}`;
}

// --- Structural checks (beyond byte-for-byte freshness) ---------------------

export function runStructuralChecks(rootDir = ROOT_DIR) {
  const results = [];
  const add = (name, ok, detail = '') => results.push({ name, ok, detail });

  const components = getPublicComponents(rootDir);
  const content = readContent(rootDir);
  const componentNames = new Set(components.map((c) => c.name));
  const contentNames = new Set(Object.keys(content.components ?? {}));

  // Every public component has a curated content entry (coverage), and vice versa.
  const missing = [...componentNames].filter((n) => !contentNames.has(n)).sort();
  add('every public component has a content entry', missing.length === 0, missing.length ? `missing: ${missing.join(', ')}` : `${componentNames.size} components`);
  const extra = [...contentNames].filter((n) => !componentNames.has(n)).sort();
  add('no content entries for unknown components', extra.length === 0, extra.length ? `unknown: ${extra.join(', ')}` : '');

  // Every content entry has a non-empty purpose.
  const emptyPurpose = [...contentNames].filter((n) => !content.components[n]?.purpose?.trim()).sort();
  add('every content entry has a purpose', emptyPurpose.length === 0, emptyPurpose.length ? `empty: ${emptyPurpose.join(', ')}` : '');

  // Every component has at least one executable showcase example.
  const usageIndex = buildShowcaseUsageIndex(rootDir);
  const noExample = components.filter((c) => usageForComponent(c, usageIndex).length === 0).map((c) => c.name);
  add('every component has an executable showcase example', noExample.length === 0, noExample.length ? `no example: ${noExample.join(', ')}` : '');

  // The generated document carries every required section for every component.
  const doc = buildDocument(rootDir);
  const perComponent = doc.split(/^## /m).slice(1);
  const sectionGaps = [];
  for (const block of perComponent) {
    const nameMatch = block.match(/^`([^`]+)`/);
    const name = nameMatch ? nameMatch[1] : '(unknown)';
    for (const section of REQUIRED_SECTIONS) {
      if (!block.includes(`**${section}`)) sectionGaps.push(`${name}:${section}`);
    }
  }
  add('generated doc carries every required section', sectionGaps.length === 0, sectionGaps.length ? `gaps: ${sectionGaps.slice(0, 8).join(', ')}${sectionGaps.length > 8 ? ' …' : ''}` : `${REQUIRED_SECTIONS.length} sections × ${perComponent.length} components`);

  const ok = results.every((r) => r.ok);
  return { ok, results };
}

// --- CLI --------------------------------------------------------------------

function writeDocument(rootDir = ROOT_DIR) {
  fs.writeFileSync(path.join(rootDir, OUTPUT_FILE), buildDocument(rootDir));
}

function main() {
  const check = process.argv.includes('--check');
  const outPath = path.join(ROOT_DIR, OUTPUT_FILE);
  const expected = buildDocument(ROOT_DIR);

  const structural = runStructuralChecks(ROOT_DIR);
  for (const r of structural.results) {
    process.stdout.write(`${r.ok ? 'ok  ' : 'FAIL'}  ${r.name}${r.detail ? ` — ${r.detail}` : ''}\n`);
  }

  if (check) {
    const actual = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
    const fresh = actual === expected;
    process.stdout.write(`${fresh ? 'ok  ' : 'FAIL'}  ${OUTPUT_FILE} is up to date\n`);
    if (!structural.ok || !fresh) {
      process.stdout.write('\nComponent reference check FAILED. Run `pnpm docs:contract:generate` and fill docs/component-reference.content.json.\n');
      process.exit(1);
    }
    process.stdout.write('\nComponent documentation contract check passed.\n');
    return;
  }

  writeDocument(ROOT_DIR);
  process.stdout.write(`\nWrote ${OUTPUT_FILE}.\n`);
  if (!structural.ok) process.exit(1);
}

const isCli = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) main();
