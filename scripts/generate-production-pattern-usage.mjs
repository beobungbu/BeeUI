#!/usr/bin/env node

/**
 * Generates the component -> production pattern mapping required by #472 section 2's
 * `production` coverage class ("link/mapping to at least one real pattern where the
 * component is used, when such a pattern exists").
 *
 * The mapping is derived from real imports in the canonical pattern screens rather than
 * hand-maintained, so it cannot drift from the patterns that actually compose a component.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  ROOT_DIR,
  extractBeeuiImports,
  getPatternRuntimeIds,
  getPatternScreens,
  getPublicComponents,
} from './component-docs-lib.mjs';

const OUTPUT = 'apps/showcase/production-pattern-usage.ts';

export function buildProductionPatternUsage(rootDir = ROOT_DIR) {
  const runtimeIds = getPatternRuntimeIds(rootDir);
  const screens = getPatternScreens(rootDir).map((screen) => ({
    id: runtimeIds.get(screen.file.split('/').pop())?.id,
    file: screen.file,
    symbols: extractBeeuiImports(fs.readFileSync(path.join(rootDir, screen.file), 'utf8')),
  }));

  const usage = {};
  for (const component of getPublicComponents(rootDir)) {
    const owned = new Set(component.values);
    const ids = screens
      .filter((screen) => [...screen.symbols].some((symbol) => owned.has(symbol)))
      .map((screen) => screen.id)
      .sort((a, b) => a.localeCompare(b));
    if (ids.length) usage[component.name] = ids;
  }
  return usage;
}

export function renderProductionPatternUsage(usage) {
  const body = Object.keys(usage)
    .sort((a, b) => a.localeCompare(b))
    .map((name) => `  '${name}': [${usage[name].map((id) => `'${id}'`).join(', ')}],`)
    .join('\n');

  return `// GENERATED by scripts/generate-production-pattern-usage.mjs — do not edit by hand.
// Run \`pnpm showcase:production-usage:generate\` after changing pattern screen composition.
//
// Maps a public component family to the production pattern screens that actually import one of
// its public symbols. #472 section 2 requires the \`production\` coverage class to be a real
// mapping to a pattern where the component is used; deriving it from imports keeps that link
// honest instead of hand-asserted.

export const PRODUCTION_PATTERN_USAGE: Readonly<Record<string, readonly string[]>> = {
${body}
};
`;
}

function main() {
  const usage = buildProductionPatternUsage(ROOT_DIR);
  const rendered = renderProductionPatternUsage(usage);
  const file = path.join(ROOT_DIR, OUTPUT);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';

  if (process.argv.includes('--check')) {
    if (current !== rendered) {
      console.error(`${OUTPUT} is stale. Run \`pnpm showcase:production-usage:generate\`.`);
      process.exitCode = 1;
      return;
    }
    console.log(`Production pattern usage mapping is current (${Object.keys(usage).length} components).`);
    return;
  }

  fs.writeFileSync(file, rendered);
  console.log(`Wrote ${OUTPUT} (${Object.keys(usage).length} components with production pattern usage).`);
}

const isCli = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) main();
